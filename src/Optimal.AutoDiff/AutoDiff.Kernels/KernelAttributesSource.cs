namespace Optimal.AutoDiff.Analyzers.Kernels
{
    /// <summary>
    /// The source the generator adds to every compilation for array kernels: the attributes that declare a kernel's
    /// derivatives and span lengths, and <c>KernelMath</c>, smooth stand-ins for min, max and abs that a kernel inlines.
    /// </summary>
    public static class KernelAttributesSource
    {
        public const string HintName = "OptimalKernelAttributes.g.cs";

        public const string Text = """
            // <auto-generated/>

            #nullable enable annotations
            #nullable disable warnings

            #pragma warning disable CS0612, CS0618, CS9113, CS1591

            using System;

            namespace Optimal
            {
                /// <summary>Declares the constant length of a span parameter of an array kernel.</summary>
                [AttributeUsage(AttributeTargets.Parameter)]
                internal sealed class FixedLengthAttribute : Attribute
                {
                    public FixedLengthAttribute(int length) => Length = length;

                    public int Length { get; }
                }

                /// <summary>
                /// Generates <c>{Kernel}Jacobian_{wrt}</c>: the dense Jacobian of the kernel's output with respect to the named
                /// input, row-major, by vector forward mode.
                /// </summary>
                [AttributeUsage(AttributeTargets.Method, AllowMultiple = true)]
                internal sealed class JacobianAttribute : Attribute
                {
                    public JacobianAttribute(string wrt) => Wrt = wrt;

                    public string Wrt { get; }

                    /// <summary>The most operations per generated method; larger kernels are split into chunks.</summary>
                    public int ChunkSize { get; set; }
                }

                /// <summary>
                /// Generates <c>{Kernel}Vjp_{wrt…}</c>: λᵀ ∂output/∂p for each named input p, by reverse mode with no tape,
                /// sharing one adjoint sweep.
                /// </summary>
                [AttributeUsage(AttributeTargets.Method, AllowMultiple = true)]
                internal sealed class VjpAttribute : Attribute
                {
                    public VjpAttribute(params string[] wrt) => Wrt = wrt;

                    public string[] Wrt { get; }

                    /// <summary>The most operations per generated method; larger kernels are split into chunks.</summary>
                    public int ChunkSize { get; set; }
                }

                /// <summary>
                /// Smooth stand-ins a kernel may call where the kink of Math.Min, Math.Max or Math.Abs would spoil a
                /// derivative. Each differs from the function it smooths by at most <c>width</c> (half of it for min and max).
                /// </summary>
                internal static class KernelMath
                {
                    public static double SmoothMin(double a, double b, double width) => 0.5 * (a + b - Math.Sqrt(((a - b) * (a - b)) + (width * width)));

                    public static double SmoothMax(double a, double b, double width) => 0.5 * (a + b + Math.Sqrt(((a - b) * (a - b)) + (width * width)));

                    public static double SmoothAbs(double x, double width) => Math.Sqrt((x * x) + (width * width));
                }
            }
            """;
    }
}
