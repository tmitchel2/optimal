using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Optimal.AutoDiff.Analyzers.Kernels
{
    /// <summary>
    /// Generates <c>{Class}Kernels</c> for each <c>[OptimalCode]</c> class with array kernels: for every
    /// <c>[Jacobian]</c> a dense Jacobian by vector forward mode, and for every <c>[Vjp]</c> a vector–Jacobian product by
    /// reverse mode, as allocation-free SSA code in a file of its own. The scalar generator's output is untouched.
    /// </summary>
    public static class KernelGenerator
    {
        /// <summary>Whether a method is an array kernel: it carries <c>[Jacobian]</c> or <c>[Vjp]</c>.</summary>
        public static bool IsKernelMethod(IMethodSymbol method)
        {
            return method.GetAttributes().Any(DerivativeRequest.IsDerivativeAttribute);
        }

        /// <summary>The metadata name of a class with array kernels, or null for any other symbol.</summary>
        public static string? KernelClassName(ISymbol symbol)
        {
            return symbol is INamedTypeSymbol type && type.GetMembers().OfType<IMethodSymbol>().Any(IsKernelMethod)
                ? MetadataName(type)
                : null;
        }

        /// <summary>Generates the kernels of each named class, reporting a diagnostic for each kernel that cannot be generated.</summary>
        public static void Generate(Compilation compilation, ImmutableArray<string?> classNames, SourceProductionContext context)
        {
            foreach (var name in classNames.OfType<string>().Distinct().OrderBy(n => n, System.StringComparer.Ordinal))
            {
                var type = compilation.GetTypeByMetadataName(name);
                if (type != null)
                {
                    GenerateClass(compilation, type, context);
                }
            }
        }

        private static void GenerateClass(Compilation compilation, INamedTypeSymbol type, SourceProductionContext context)
        {
            var library = new KernelFunctionLibrary(compilation);
            var methods = new StringBuilder();
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(IsKernelMethod))
            {
                var syntax = method.DeclaringSyntaxReferences.Select(r => r.GetSyntax(context.CancellationToken)).OfType<MethodDeclarationSyntax>().FirstOrDefault();
                if (syntax == null)
                {
                    continue;
                }

                try
                {
                    _ = methods.Append(GenerateKernel(method, syntax, library, context.CancellationToken));
                }
                catch (KernelException ex)
                {
                    var location = ex.Location ?? (ex.Node == null ? null : library.LocationOf(ex.Node)) ?? syntax.Identifier.GetLocation();
                    context.ReportDiagnostic(Diagnostic.Create(ex.Descriptor, location, method.Name, ex.Message));
                }
            }

            var namespaceName = type.ContainingNamespace.IsGlobalNamespace ? "Generated" : type.ContainingNamespace.ToDisplayString();
            var accessibility = type.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
            var sb = new StringBuilder();
            _ = sb.AppendLine("// <auto-generated/>")
                .AppendLine("#nullable enable")
                .AppendLine()
                .AppendLine("using System;")
                .AppendLine("using System.Runtime.CompilerServices;")
                .AppendLine()
                .AppendLine($"namespace {namespaceName}")
                .AppendLine("{")
                .AppendLine($"    /// <summary>Derivatives of the array kernels of {type.Name}, generated by Optimal.AutoDiff.</summary>")
                .AppendLine($"    {accessibility} static partial class {type.Name}Kernels")
                .AppendLine("    {")
                .AppendLine("        [MethodImpl(MethodImplOptions.NoInlining)]")
                .AppendLine("        private static void ThrowLength(string name, int length)")
                .AppendLine("        {")
                .AppendLine("            throw new ArgumentException($\"Expected a span of length {length}.\", name);")
                .AppendLine("        }")
                .AppendLine()
                .Append(methods)
                .AppendLine("    }")
                .AppendLine("}");
            context.AddSource(HintName(type), SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static string GenerateKernel(IMethodSymbol method, MethodDeclarationSyntax syntax, KernelFunctionLibrary library, CancellationToken cancellationToken)
        {
            var parameters = KernelSignature.Analyze(method, syntax);
            var requests = method.GetAttributes()
                .Where(DerivativeRequest.IsDerivativeAttribute)
                .Select(a => DerivativeRequest.From(a, parameters, syntax.Identifier.GetLocation()))
                .ToList();
            var duplicate = requests.GroupBy(r => r.MethodName(method.Name)).FirstOrDefault(g => g.Count() > 1);
            if (duplicate != null)
            {
                throw new KernelException(KernelDiagnostics.InvalidDerivativeAttribute, duplicate.Last().Location, $"'{duplicate.Key}' is requested twice");
            }

            var kernel = new LoopUnroller(library, cancellationToken).Unroll(library.Kernel(method, syntax), parameters);
            var inputs = parameters.Where(p => !p.IsOutput).ToList();
            var taken = new HashSet<string>(parameters.Select(p => p.Name));
            var sb = new StringBuilder();
            foreach (var request in requests)
            {
                var emitter = new KernelCodeEmitter(request.ChunkSize);
                var name = request.MethodName(method.Name);
                _ = sb.Append(request.IsJacobian
                    ? EmitJacobian(emitter, name, method.Name, kernel, inputs, request.Wrt[0], taken)
                    : EmitVjp(emitter, name, method.Name, kernel, inputs, request.Wrt, taken));
            }

            return sb.ToString();
        }

        private static string EmitJacobian(KernelCodeEmitter emitter, string name, string kernelName, UnrolledKernel kernel, List<KernelParameter> inputs, KernelParameter wrt, ISet<string> taken)
        {
            var jacobian = new KernelOutput(Unique("jacobian", taken), JacobianTransform.Apply(kernel, wrt));
            var summary = $"∂{kernel.Output.Name}/∂{wrt.Name} of {kernelName}, row-major ({kernel.Output.Length} × {wrt.Length}).";
            return emitter.Emit(name, summary, kernel.Graph, inputs, new[] { jacobian });
        }

        private static string EmitVjp(KernelCodeEmitter emitter, string name, string kernelName, UnrolledKernel kernel, List<KernelParameter> inputs, ImmutableArray<KernelParameter> wrt, ISet<string> taken)
        {
            var lambda = new KernelParameter(Unique("lambda", taken), kernel.Output.Length, IsArray: true, IsOutput: false, kernel.Parameters.Length);
            var gradients = VjpTransform.Apply(kernel, wrt, lambda.Group);
            var outputs = wrt
                .Select((w, i) => new KernelOutput(Unique(wrt.Length == 1 ? "gradient" : $"gradient{char.ToUpperInvariant(w.Name[0])}{w.Name.Substring(1)}", taken), gradients[i]))
                .ToList();
            var summary = $"λᵀ ∂{kernel.Output.Name}/∂({string.Join(", ", wrt.Select(w => w.Name))}) of {kernelName}, with λ in {lambda.Name}.";
            return emitter.Emit(name, summary, kernel.Graph, inputs.Append(lambda).ToList(), outputs);
        }

        // A generated parameter name that does not clash with the kernel's own.
        private static string Unique(string name, ISet<string> taken)
        {
            var unique = name;
            while (taken.Contains(unique))
            {
                unique += "_";
            }

            return unique;
        }

        private static string MetadataName(INamedTypeSymbol type)
        {
            if (type.ContainingType != null)
            {
                return MetadataName(type.ContainingType) + "+" + type.MetadataName;
            }

            return type.ContainingNamespace.IsGlobalNamespace ? type.MetadataName : type.ContainingNamespace.ToDisplayString() + "." + type.MetadataName;
        }

        private static string HintName(INamedTypeSymbol type)
        {
            var name = new string(type.ToDisplayString().Select(c => char.IsLetterOrDigit(c) || c is '.' or '_' ? c : '_').ToArray());
            return $"{name}Kernels.g.cs";
        }
    }
}
